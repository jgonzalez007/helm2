"""Stage 2: Claude decides the cases the rules could not settle.

Three hard limits, in order of how much they matter.

1. **Stage 2 never sets urgency.** Urgency comes from calendar times, parsed
   deadlines and thread state — all structured, all local, all free. Letting a
   model infer urgency from text is exactly the hole the whole flag design exists
   to close, so `apply()` only ever writes importance and drops any urgency the
   model volunteers.

2. **No message body is sent.** `payload()` builds its dict from a named list of
   metadata fields and never touches `snippet`. The subject goes, because the
   brief lists topic keywords as a legitimate importance signal and the subject is
   a structured field — but it can only move importance, never urgency.

3. **A sender is classified once.** The verdict is written to `sender_profile`, so
   the next hundred messages from `health@aws.com` cost nothing. This is the
   durable replacement for the hardcoded pattern list in `mail_source`.

Batched, cached, and re-run only when the rules say something changed.
"""

from __future__ import annotations

from datetime import datetime, timedelta, timezone

from . import claude_cli as cli
from . import flags as flagmod
from .models import Flag, Item, now_iso

BATCH = 20
IMPORTANCE = ("high", "normal", "low")

# Exactly the fields stage 2 may see. Anything not named here cannot reach the
# model, which is why this is a list rather than an exclusion.
PAYLOAD_FIELDS = ("id", "source", "kind", "subject", "sender", "sender_addr",
                  "sender_external", "to_me_direct", "cc_me")

PROMPT = """You are triaging work messages for one person. For each item below, \
judge only how much it matters to them.

You are given metadata only: who sent it, whether they are outside the company, \
whether the person was on To: or Cc:, and the subject line. You do not get the \
message body, and you must not ask for it.

Judge, per item:
  importance    "high" if a person is likely waiting on this person's own decision,
                answer or sign-off; "normal" for work they should see but nobody is
                blocked on; "low" for notifications, digests, marketing and anything
                generated by a system.
  is_automated  true if the sender is a system, a ticketing or approval workflow, a
                digest, a mailing list or a marketing sender, rather than a person
                typing to this person.
  expects_reply true only if a human would expect a written answer back.
  confidence    0.0 to 1.0, your own confidence in this judgement.
  reason        under 12 words, naming the signal you used.

Do NOT judge urgency, deadlines or timing. Those are decided elsewhere from the
calendar and from parsed dates, and anything you say about them is discarded.

Items:
{items}

Reply with ONLY a JSON array, one object per item, keys exactly:
id, importance, is_automated, expects_reply, confidence, reason
"""


def payload(item: Item) -> dict:
    """Metadata only. Structurally cannot carry a message body."""
    out = {}
    for field in PAYLOAD_FIELDS:
        value = getattr(item, field, "")
        out[field] = bool(value) if isinstance(value, bool) else str(value)[:300]
    return out


def render(items: list[Item]) -> str:
    lines = []
    for item in items:
        p = payload(item)
        lines.append(
            f'- id: {p["id"]}\n'
            f'  from: {p["sender"]} <{p["sender_addr"]}>'
            f'{" (outside the company)" if p["sender_external"] else " (colleague)"}\n'
            f'  addressed: {"To: them" if p["to_me_direct"] else ("Cc: them" if p["cc_me"] else "a list or shared mailbox")}\n'
            f'  kind: {p["source"]} {p["kind"]}\n'
            f'  subject: {p["subject"]}')
    return "\n".join(lines)


def candidates(items: list[Item], flags: dict[str, Flag], cfg: flagmod.Settings,
                profiles: dict[str, dict], now: datetime | None = None) -> list[Item]:
    """Which items stage 2 should see. Everything else is already settled or cached."""
    now = now or datetime.now(timezone.utc)
    cfg = cfg.normalized()
    out: list[Item] = []
    for item in items:
        flag = flags.get(item.id)
        if flag is not None and flag.pinned:
            continue                      # the user decided; never ask
        if flag is not None and flag.decided_by == "claude" and not _stale(flag, now):
            continue                      # cached verdict still good
        addr = (item.sender_addr or "").lower()
        if addr and addr in profiles:
            continue                      # this sender is already known
        sig = flagmod._signals(item, cfg, now)
        _, _, _, confident = flagmod._score(sig)
        if confident:
            continue                      # the rules settled it for free
        out.append(item)
    return out


def _stale(flag: Flag, now: datetime) -> bool:
    if not flag.recheck_after:
        return True
    try:
        return datetime.fromisoformat(flag.recheck_after) <= now
    except ValueError:
        return True


def _clean_verdict(raw) -> dict | None:
    if not isinstance(raw, dict):
        return None
    item_id = str(raw.get("id") or "")[:300]
    if not item_id:
        return None
    importance = str(raw.get("importance") or "").strip().lower()
    if importance not in IMPORTANCE:
        importance = "normal"
    try:
        confidence = min(1.0, max(0.0, float(raw.get("confidence", 0.5))))
    except (TypeError, ValueError):
        confidence = 0.5
    return {
        "id": item_id,
        "importance": importance,
        "is_automated": bool(raw.get("is_automated")),
        "expects_reply": bool(raw.get("expects_reply", True)),
        "confidence": confidence,
        "reason": str(raw.get("reason") or "")[:140],
    }


def classify_batch(items: list[Item], timeout: int | None = None) -> list[dict]:
    """One connector call for up to BATCH items. Metadata only."""
    if not items:
        return []
    prompt = PROMPT.format(items=render(items[:BATCH]))
    # No tools at all: this is a judgement about metadata already in hand, so the
    # model has nothing to look up and no way to reach the mailbox.
    reply, _ = cli.run_once(prompt, (), timeout=timeout or cli.ONE_SHOT_TIMEOUT)
    parsed = cli.extract_json(reply)
    if not isinstance(parsed, list):
        raise cli.ClaudeUnavailable(f"could not read the verdicts: {reply[:160]}")
    known = {i.id for i in items[:BATCH]}
    verdicts = [v for v in (_clean_verdict(r) for r in parsed) if v is not None]
    return [v for v in verdicts if v["id"] in known]


def apply(verdict: dict, flag: Flag, now_str: str | None = None) -> Flag:
    """Write a verdict onto a flag. Importance only — urgency is never touched.

    A pinned flag is returned unchanged: the user's override outranks any model.
    """
    if flag.pinned:
        return flag
    before = flag.urgency
    flag.importance = verdict["importance"]
    flag.decided_by = "claude"
    flag.confidence = verdict["confidence"]
    flag.evaluated_at = now_str or now_iso()
    reason = verdict.get("reason") or "no reason given"
    flag.reasons = [r for r in flag.reasons if r.get("rule") != "claude"]
    flag.reasons.append({"rule": "claude", "detail": reason})
    # Belt and braces: even if a future edit lets a verdict carry urgency, it cannot
    # land. Urgency is decided by the rules and nothing else.
    flag.urgency = before
    return flag


def profile_from(verdict: dict) -> dict:
    """The part of a verdict worth remembering about the sender, not the message."""
    return {
        "is_automated": verdict["is_automated"],
        "expects_reply": verdict["expects_reply"],
        "importance_hint": verdict["importance"] if verdict["is_automated"] else "",
        "reason": verdict.get("reason", ""),
        "decided_by": "claude",
        "confidence": verdict["confidence"],
    }


def next_recheck(now: datetime | None = None, hours: int = 72) -> str:
    """A cached verdict about a sender does not need revisiting often."""
    now = now or datetime.now(timezone.utc)
    return (now + timedelta(hours=hours)).isoformat(timespec="seconds")
